#!/usr/bin/env python3
"""Compile the versioned local ingredient groups; no runtime AI edits."""
import json
from pathlib import Path
entries = json.loads(Path('data/fixtures/ingredients.json').read_text())['entries']
lines = ['// Generated by scripts/generate-ingredients.py.', 'package huaiwei.agent', '', 'import huaiwei.model.*', '', 'let builtInIngredientGroups: Array<IngredientAssociation> = [']
for entry in entries:
    name = json.dumps(entry['ingredient'], ensure_ascii=False)
    related = json.dumps(entry['related'], ensure_ascii=False)
    lines.append(f'        IngredientAssociation(ingredient: {name}, related: {related}),')
lines.extend([']', '', 'func localIngredientGroups(): Array<IngredientAssociation> { builtInIngredientGroups }', ''])
Path('src/agent/ingredient_groups.cj').write_text('\n'.join(lines))
